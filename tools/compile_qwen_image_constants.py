#!/usr/bin/env python3
"""Freeze small FP32 frequency tables; no inference-time Python dependency.

Diffusers aea7b70b initializes these on the CPU before device placement.
Hexadecimal constants preserve the frozen PyTorch CPU rounding exactly.
"""

import argparse
from pathlib import Path
import math
import torch


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("output", type=Path)
    a = p.parse_args()
    tables = {
        "qi_dit_rope_frequency": torch.cat(
            [1 / torch.pow(10000, torch.arange(0, d, 2).float() / d) for d in (16, 56)]
        ),
        "qi_dit_time_frequency": torch.exp(
            -math.log(10000) * torch.arange(128, dtype=torch.float32) / 128
        ),
    }
    text = "/* Generated by tools/compile_qwen_image_constants.py; frozen Diffusers aea7b70b. */\n"
    for name, values in tables.items():
        text += f"static const float {name}[{len(values)}] = {{\n"
        for i in range(0, len(values), 4):
            text += (
                "  "
                + ", ".join(float(v).hex() + "f" for v in values[i : i + 4])
                + ",\n"
            )
        text += "};\n"
    a.output.write_text(text)


if __name__ == "__main__":
    main()
