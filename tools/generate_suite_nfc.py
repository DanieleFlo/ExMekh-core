#!/usr/bin/env python3
"""Regenerate the image tokenizer's exact Unicode 9 NFC tables.

Source: unicode-normalization-alignments 0.1.12, already linked into the frozen
tokenizers wheel. Preserve its Unicode version rather than upgrading semantics.
Only table data are converted; the native normalization implementation is C.
"""

import argparse
import hashlib
import io
import re
import tarfile
from pathlib import Path

SHA = "43f613e4fa046e69818dd287fdc4bc78175ff20331479dab6e1b0f98d57062de"
PREFIX = "unicode-normalization-alignments-0.1.12/"


def generate(crate, output):
    raw = crate.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA:
        raise ValueError("crate identity mismatch")
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as archive:
        text = archive.extractfile(PREFIX + "src/tables.rs").read().decode()
        license_text = archive.extractfile(PREFIX + "LICENSE-MIT").read()

    def section(name):
        return re.search(rf"const {name}:.*?= &\[(.*?)\n\];", text, re.DOTALL)[1]

    classes = sorted(
        int(x, 16)
        for x in re.findall(
            r"0x([0-9A-Fa-f]+)", section("CANONICAL_COMBINING_CLASS_KV")
        )
    )
    compositions = []
    for key, value in re.findall(
        r"\(0x([0-9a-fA-F]+), '\\u\{([0-9a-fA-F]+)\}'\)",
        section("COMPOSITION_TABLE_KV"),
    ):
        pair = int(key, 16)
        compositions.append(((pair >> 16) << 21 | (pair & 65535), int(value, 16)))
    astral = text.split("fn composition_table_astral", 1)[1].split("_ => None", 1)[0]
    for left, right, value in re.findall(
        r"\('\\u\{([0-9a-fA-F]+)\}', '\\u\{([0-9a-fA-F]+)\}'\) => Some\('\\u\{([0-9a-fA-F]+)\}'\)",
        astral,
    ):
        compositions.append((int(left, 16) << 21 | int(right, 16), int(value, 16)))
    decompositions = []
    for cp, values in re.findall(
        r"\(0x([0-9a-fA-F]+), &\[(.*?)\]\)", section("CANONICAL_DECOMPOSED_KV")
    ):
        codepoints = [int(c, 16) for c in re.findall(r"\\u\{([0-9a-fA-F]+)\}", values)]
        decompositions.append((int(cp, 16), codepoints))
    lines = [
        "/* Generated by tools/generate_suite_nfc.py; Unicode 9.0.0.",
        " * Copyright 2012-2019 The Rust Project Developers. MIT; see LICENSE.",
        f" * Source crate SHA-256: {SHA}. */",
        "static const uint32_t nfc_classes[] = {",
    ]
    lines += [f"0x{x:x}," for x in classes]
    lines += [
        "};",
        "typedef struct {uint64_t key;uint32_t value;} nfc_composition;",
        "static const nfc_composition nfc_compositions[] = {",
    ]
    lines += [f"{{UINT64_C(0x{k:x}),0x{v:x}}}," for k, v in sorted(compositions)]
    flattened = []
    records = []
    for cp, values in sorted(decompositions):
        records.append((cp, len(flattened), len(values)))
        flattened.extend(values)
    lines += ["};", "static const uint32_t nfc_decomposed[] = {"]
    lines += [f"0x{x:x}," for x in flattened]
    lines += [
        "};",
        "typedef struct {uint32_t cp,offset,length;} nfc_decomposition;",
        "static const nfc_decomposition nfc_decompositions[] = {",
    ]
    lines += [f"{{0x{cp:x},{offset},{length}}}," for cp, offset, length in records]
    lines += ["};", ""]
    output.mkdir(parents=True, exist_ok=True)
    (output / "nfc9.inc").write_text("\n".join(lines))
    (output / "LICENSE").write_bytes(license_text)
    print(
        f"NFC9: {len(classes)} combining classes, {len(compositions)} compositions, {len(records)} decompositions"
    )


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("crate", type=Path)
    p.add_argument("output", type=Path)
    args = p.parse_args()
    generate(args.crate, args.output)
