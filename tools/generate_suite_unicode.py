#!/usr/bin/env python3
"""Compile character classes from the pinned tokenizers regex engine.

The image tokenizer must not inherit the legacy Qwen tokenizer's newer Unicode
version. This generates data, not a Python dependency for native inference.
"""

import argparse
import hashlib
import importlib
import json
import sys
from pathlib import Path


def generate(deps, output):
    sys.path.insert(0, str(deps))
    import tokenizers
    from tokenizers import Regex, pre_tokenizers

    if tokenizers.__version__ != "0.23.1":
        raise ValueError("expected frozen tokenizers 0.23.1")
    binary = Path(importlib.import_module("tokenizers.tokenizers").__file__)
    digest = hashlib.sha256(binary.read_bytes()).hexdigest()
    text = "".join(chr(cp) for cp in range(1, 0x110000) if not 0xD800 <= cp <= 0xDFFF)
    lines = [
        "/* Generated by tools/generate_suite_unicode.py from tokenizers 0.23.1.",
        f" * Frozen regex engine SHA-256: {digest}. */",
        "typedef struct { uint32_t lo, hi; } ds4_image_urange;",
    ]
    report = {
        "tokenizers": tokenizers.__version__,
        "engine_sha256": digest,
        "classes": {},
    }
    for name, pattern in [("letter", r"\p{L}"), ("number", r"\p{N}"), ("space", r"\s")]:
        selected = bytearray(b"\1") * 0x110000
        selected[0] = 0
        selected[0xD800:0xE000] = bytes(0x800)
        for piece, _ in pre_tokenizers.Split(
            Regex(pattern), behavior="removed"
        ).pre_tokenize_str(text):
            for cp in map(ord, piece):
                selected[cp] = 0
        lines.append(f"static const ds4_image_urange ds4_image_{name}_ranges[] = {{")
        start = None
        ranges = 0
        for cp in range(0x110001):
            active = cp < 0x110000 and selected[cp]
            if active and start is None:
                start = cp
            elif not active and start is not None:
                lines.append(f"{{0x{start:x}, 0x{cp - 1:x}}},")
                start = None
                ranges += 1
        lines.append("};")
        report["classes"][name] = {"ranges": ranges, "scalars": sum(selected)}
    output.write_text("\n".join(lines) + "\n")
    return report


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--deps", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    print(json.dumps(generate(args.deps, args.output), indent=2))
